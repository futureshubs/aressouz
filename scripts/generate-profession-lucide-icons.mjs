const iconNames = new Set([...Object.values(MAP), ...Object.values(CATEGORY)]);

const lines = [];
lines.push("import type { LucideIcon } from 'lucide-react';");
lines.push('import {');
lines.push([...iconNames].sort().map((n) => `  ${n},`).join('\n'));
lines.push("} from 'lucide-react';");
lines.push('');
lines.push('const ICONS = {');
for (const name of [...iconNames].sort()) {
  lines.push(`  ${name},`);
}
lines.push('} as const satisfies Record<string, LucideIcon>;');
lines.push('');
lines.push('type IconName = keyof typeof ICONS;');
lines.push('');
lines.push('const CATEGORY_ICON: Record<string, IconName> = {');
for (const [k, v] of Object.entries(CATEGORY)) {
  lines.push(`  ${k}: '${v}',`);
}
lines.push('};');
lines.push('');
lines.push('const PROFESSION_ICON: Partial<Record<string, IconName>> = {');
for (const [k, v] of Object.entries(MAP)) {
  const safe = k.replace(/\\/g, '\\\\').replace(/'/g, "\\'");
  lines.push(`  '${safe}': '${v}',`);
}
lines.push('};');
lines.push('');
lines.push('export function getProfessionLucideIcon(name: string, categoryId: string): LucideIcon {');
lines.push("  const key = PROFESSION_ICON[name] ?? CATEGORY_ICON[categoryId] ?? 'Briefcase';");
lines.push('  return ICONS[key];');
lines.push('}');
lines.push('');

writeFileSync('src/app/data/professionLucideIcons.ts', lines.join('\n'), 'utf8');
console.log('icons', iconNames.size, 'professions', Object.keys(MAP).length);
